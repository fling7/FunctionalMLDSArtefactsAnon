"""Generate the invariant evidence ledger from canonical declarations and registry."""
from __future__ import annotations
import csv
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from tools.dynamic_functional_rdl_v2_model import MODEL
from tools.validate_dynamic_functional_rdl_v2 import INVARIANT_CHECK_REGISTRY


def main():
    rows=[]
    for invariant in MODEL['invariants']:
        entry=INVARIANT_CHECK_REGISTRY[invariant['id']]
        rows.append({'invariant':invariant['id'],'profile':invariant['profile'],'severity':invariant['severity'],'status':entry['status'],'check_codes':'; '.join(entry['check_codes']),'fixture':entry['fixture'],'evidence':entry['evidence'],'meaning':invariant['text']})
    out=ROOT/'docs'
    out.mkdir(exist_ok=True)
    with (out/'INVARIANT_TRACEABILITY.csv').open('w',encoding='utf-8',newline='') as stream:
        writer=csv.DictWriter(stream,fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    lines=['# Invariant enforcement traceability','',
           'Generated by `python tools/generate_invariant_traceability.py` from `tools/dynamic_functional_rdl_v2_model.py` and `INVARIANT_CHECK_REGISTRY` in `tools/validate_dynamic_functional_rdl_v2.py`. Do not edit this ledger by hand.','',
           'An invariant declaration, descriptor-shape check, or synchronization check does not by itself demonstrate enforcement of that invariant on instances. The registry credits an old invariant only when its full stated condition has an explicit check and a negative fixture that exercises it. `not enforced` means no complete enforcement evidence has been registered; it does not mean that no related structural check exists. No percentage of all 81 invariants is claimed as runtime coverage.','',
           'The current audited old entries are INV-064 and INV-065. The other 72 old statements remain uncredited pending individual audits. New checks INV-075–081 are exercised by a common passing example-derived fixture and the per-invariant negative fixtures below. INV-079 is a warning and INV-080 is a report, so a triggered check does not always invalidate publication. INV-081 requires serialized bytes and both project/trace metadata; in-memory routing analysis reports it as not evaluated.','',
           'The existing structural instance validator remains the default. `--profile executable --instance ... --trace ... --project ...` additionally invokes Gate 0. All per-invariant negative checks are in `tests/test_routing_verifier.py`; passing fixture: `tests/fixtures/routing/pass.json`. These small semantic fixtures intentionally omit unrelated authoring scaffolding.','',
           '| Invariant | Profile | Status | Check code | Negative fixture | Evidence |','| --- | --- | --- | --- | --- | --- |']
    for row in rows:
        vals=[row[k] or '—' for k in ['invariant','profile','status','check_codes','fixture','evidence']]
        lines.append('| '+' | '.join(v.replace('|','\\|') for v in vals)+' |')
    (out/'INVARIANT_TRACEABILITY.md').write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    print(f'Generated traceability for {len(rows)} invariants.')

if __name__=='__main__': main()
